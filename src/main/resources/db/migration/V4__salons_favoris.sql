-- V4 — Salons favoris d'un client (remplace les favoris « barbier » supprimés en V3).
CREATE TABLE IF NOT EXISTS salon_favorites (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id   BIGINT    NOT NULL REFERENCES clients(id) ON DELETE CASCADE,
    salon_id    BIGINT    NOT NULL REFERENCES salons(id)  ON DELETE CASCADE,
    created_at  TIMESTAMP NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_salon_favorite UNIQUE (client_id, salon_id)
);

CREATE INDEX IF NOT EXISTS idx_salon_favorite_client ON salon_favorites (client_id);
