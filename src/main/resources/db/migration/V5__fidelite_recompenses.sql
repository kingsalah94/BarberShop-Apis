-- V5 — Fidélité : prestations offertes consommées (1 récompense = 10 visites payées dans un salon).
CREATE TABLE IF NOT EXISTS loyalty_rewards (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id       BIGINT    NOT NULL REFERENCES clients(id)        ON DELETE CASCADE,
    salon_id        BIGINT    NOT NULL REFERENCES salons(id)         ON DELETE CASCADE,
    queue_entry_id  BIGINT    NOT NULL REFERENCES queue_entries(id)  ON DELETE CASCADE,
    redeemed_at     TIMESTAMP NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_loyalty_reward_entry UNIQUE (queue_entry_id)
);

CREATE INDEX IF NOT EXISTS idx_loyalty_reward_client_salon ON loyalty_rewards (client_id, salon_id);
