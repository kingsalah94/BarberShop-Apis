-- V6 — Notes privées d'un salon sur un client (remplace la note globale du client, visible de tous les salons).
CREATE TABLE IF NOT EXISTS salon_client_notes (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    salon_id            BIGINT    NOT NULL REFERENCES salons(id)  ON DELETE CASCADE,
    client_id           BIGINT    NOT NULL REFERENCES clients(id) ON DELETE CASCADE,
    note                TEXT      NOT NULL,
    updated_by_user_id  BIGINT,
    updated_at          TIMESTAMP NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_salon_client_note UNIQUE (salon_id, client_id)
);
